/**
 * Transport-agnostic handlers for the public careers API. Azure Functions
 * (production) and Nitro server routes (local dev + build-time prerendering)
 * are thin adapters over these, so both expose an identical contract:
 *
 *   GET /api/careers?limit=&page=   -> PaginatedCareers
 *   GET /api/careers/{slug}         -> Career | 404
 */
import {
  MAX_PAGE_SIZE,
  PayloadConfigError,
  fetchPublishedCareer,
  fetchPublishedCareers,
  payloadConfigFromEnv,
} from './payload-client'
import type { ApiError, Career, PaginatedCareers } from './types'

export interface ApiResult<T> {
  status: number
  body: T | ApiError
  headers: Record<string, string>
}

type Env = Record<string, string | undefined>

const CACHE_OK = { 'Cache-Control': 'public, max-age=60, s-maxage=300' }
const CACHE_NONE = { 'Cache-Control': 'no-store' }

// Lowercase kebab-case, as generated by typical Payload slug fields.
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export function isValidSlug(slug: unknown): slug is string {
  return typeof slug === 'string' && slug.length <= 200 && SLUG_PATTERN.test(slug)
}

function clampInt(raw: string | null | undefined, fallback: number, min: number, max: number) {
  const value = Number.parseInt(raw ?? '', 10)
  if (!Number.isFinite(value)) return fallback
  return Math.min(max, Math.max(min, value))
}

export function parsePagination(query: URLSearchParams) {
  return {
    limit: clampInt(query.get('limit'), 10, 1, MAX_PAGE_SIZE),
    page: clampInt(query.get('page'), 1, 1, 10_000),
  }
}

function failure(error: unknown, log: (message: string, error: unknown) => void, what: string) {
  log(`Failed to retrieve ${what}`, error)
  // Misconfiguration is a server fault (500); an upstream failure is a bad gateway (502).
  const status = error instanceof PayloadConfigError ? 500 : 502
  return { status, body: { error: `Unable to retrieve ${what}` }, headers: CACHE_NONE }
}

export async function handleListCareers(
  query: URLSearchParams,
  env: Env,
  log: (message: string, error: unknown) => void = console.error,
): Promise<ApiResult<PaginatedCareers>> {
  try {
    const config = payloadConfigFromEnv(env)
    const body = await fetchPublishedCareers(config, parsePagination(query))
    return { status: 200, body, headers: CACHE_OK }
  } catch (error) {
    return failure(error, log, 'careers')
  }
}

export async function handleGetCareer(
  slug: unknown,
  env: Env,
  log: (message: string, error: unknown) => void = console.error,
): Promise<ApiResult<Career>> {
  if (!isValidSlug(slug)) {
    return { status: 400, body: { error: 'Invalid career slug' }, headers: CACHE_NONE }
  }

  try {
    const config = payloadConfigFromEnv(env)
    const career = await fetchPublishedCareer(config, slug)
    if (!career) {
      // Short cache so a newly published career path appears quickly.
      return { status: 404, body: { error: 'Career not found' }, headers: { 'Cache-Control': 'public, max-age=30' } }
    }
    return { status: 200, body: career, headers: CACHE_OK }
  } catch (error) {
    return failure(error, log, 'career')
  }
}
